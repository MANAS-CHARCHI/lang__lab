from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain.tools import tool
from langchain_core.messages import HumanMessage
from langchain_anthropic import ChatAnthropic
from tavily import TavilyClient
from pydantic import BaseModel, Field
from typing import List

tavily = TavilyClient()
load_dotenv()

class Source(BaseModel):
    """Schema for a source used by the agent"""

    url: str = Field(description="The URL of the source")

class AgentResponse(BaseModel):
    """Schema for the agent's response"""

    answer: str = Field(description="The answer generated by the agent")
    sources: List[Source] = Field(default_factory=list, description="List of sources used to generate the answer")



def search(query: str) -> str:
    """
    Tool that searches over internet
    Args:
        query (str): The search query
    Returns:
        str: The search results
    """
    print(f"Searching for: {query}")
    return tavily.search(query = query)

llm = ChatAnthropic(model="claude-haiku-5-5")
tools = [search]
agent = create_agent(model=llm, tools=tools, response_format=AgentResponse)

def main():
    print("Hello from lang-understand!")
    result = agent.invoke({"messages": HumanMessage(content="Find the best stock to buy in india?")})
    print(result)

if __name__ == "__main__":
    main()
